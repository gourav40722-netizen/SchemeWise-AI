function formatMessage(template, values = {}) {
  return Object.entries(values).reduce((text, [key, value]) => text.replaceAll(`{${key}}`, value), template);
}

const LanguageContext = createContext(null);

export function LanguageProvider({ children }) {
  const [language, setLanguageState] = useState(() => localStorage.getItem(LANGUAGE_STORAGE_KEY) || 'en');

  const setLanguage = (nextLanguage) => {
    setLanguageState(nextLanguage);
    localStorage.setItem(LANGUAGE_STORAGE_KEY, nextLanguage);
  };

  const value = useMemo(() => {
    const dictionary = translations[language] || translations.en;
    const fallback = translations.en;
    const currentLanguage = languages.find((item) => item.code === language) || languages[0];

    return {
      language,
      languages,
      currentLanguage,
      setLanguage,
      t: (key, values) => formatMessage(dictionary[key] || fallback[key] || key, values),
      categoryLabel: (category) => dictionary[`category.${category}`] || fallback[`category.${category}`] || category
    };
  }, [language]);

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) {
    throw new Error('useLanguage must be used inside LanguageProvider');
  }
  return context;
}
